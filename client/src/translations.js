export function getTranslations(language = 'English', section = 'app') {
  const englishSection = translations.English[section] || {};
  const selectedSection = translations[language]?.[section] || {};
  return new Proxy(englishSection, {
    get(target, property) {
      if (typeof property !== 'string') return target[property];
      return selectedSection[property] ?? target[property] ?? property;
    },
  });
}

export function translate(language = 'English', key, section = 'app') {
  const selected = translations[language]?.[section]?.[key];
  const fallback = translations.English[section]?.[key];
  return selected ?? fallback ?? key;
}

